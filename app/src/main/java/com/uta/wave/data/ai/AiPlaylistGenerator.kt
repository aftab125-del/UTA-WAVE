package com.uta.wave.data.ai

import android.content.Context
import com.uta.wave.data.innertube.InnerTubeClient
import com.uta.wave.data.innertube.TrackItem
import com.uta.wave.data.local.LocalDatabase
import com.uta.wave.data.preferences.UserPreferences
import com.uta.wave.player.AppLogger
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

data class AiGeneratedPlaylistResult(
    val playlistId: String,
    val name: String,
    val description: String,
    val tracks: List<TrackItem>
)

object AiPlaylistGenerator {

    private val httpClient = OkHttpClient.Builder()
        .connectTimeout(30, TimeUnit.SECONDS)
        .readTimeout(60, TimeUnit.SECONDS)
        .writeTimeout(30, TimeUnit.SECONDS)
        .build()

    private val innerTubeClient = InnerTubeClient()

    suspend fun generatePlaylist(
        context: Context,
        prompt: String,
        songCount: Int = 15,
        onProgress: (step: String, current: Int, total: Int) -> Unit = { _, _, _ -> }
    ): AiGeneratedPlaylistResult? = withContext(Dispatchers.IO) {
        val prefs = UserPreferences.getInstance(context)
        val localDatabase = LocalDatabase.getInstance(context)
        val apiKey = prefs.currentSettings.aiApiKey.trim()
        val provider = prefs.currentSettings.aiProvider

        onProgress("Consulting AI Music Curator...", 0, songCount)
        AppLogger.i("Starting AI playlist generation for prompt: \"$prompt\" (count: $songCount)")

        val systemPrompt = """
            You are a master music curator and DJ with encyclopedic knowledge of all genres, eras, and moods.
            The user will give you a mood, vibe, genre, or activity description.
            You must output ONLY a valid JSON object with:
            1. "name": A creative, evocative, cinematic title for the playlist (2 to 5 words).
            2. "description": A captivating 1-2 sentence description highlighting the sonic aesthetic and artists.
            3. "songs": A list of exactly $songCount REAL, highly-acclaimed songs that perfectly match the vibe.
               Each song object MUST have:
               - "title": exact song title
               - "artist": primary performing artist

            CRITICAL FORMAT RULE:
            Output ONLY raw JSON. Do NOT include Markdown formatting (no ```json or ``` code blocks).
            
            Format:
            {
              "name": "Midnight Neon Mirage",
              "description": "Synthwave, retrowave & atmospheric electronic rhythms for late-night highway drives.",
              "songs": [
                {"title": "Resonance", "artist": "HOME"},
                {"title": "Tech Noir", "artist": "Gunship"}
              ]
            }
        """.trimIndent()

        val rawAiResponse = callAiLlm(
            userPrompt = "Vibe/Theme: $prompt\nSong count: $songCount songs",
            systemPrompt = systemPrompt,
            apiKey = apiKey,
            provider = provider
        )

        if (rawAiResponse.isNullOrBlank()) {
            AppLogger.e("AI provider returned empty response")
            onProgress("AI connection failed. Please check your network or API key in Settings.", 0, songCount)
            return@withContext null
        }

        onProgress("Parsing playlist structure...", 0, songCount)
        val cleanJson = cleanJsonString(rawAiResponse)

        val parsedJson = try {
            JSONObject(cleanJson)
        } catch (e: Exception) {
            AppLogger.e("Failed to parse AI JSON response: $rawAiResponse", e)
            onProgress("Failed to parse music curator response.", 0, songCount)
            return@withContext null
        }

        val playlistName = parsedJson.optString("name", "AI: $prompt")
        val playlistDesc = parsedJson.optString("description", "Curated with UTA-WAVE AI Studio")
        val songsArray = parsedJson.optJSONArray("songs")

        if (songsArray == null || songsArray.length() == 0) {
            AppLogger.e("No songs array in AI response")
            onProgress("No songs generated by AI model.", 0, songCount)
            return@withContext null
        }

        val totalSongsToSearch = songsArray.length()
        val resolvedTracks = mutableListOf<TrackItem>()

        for (i in 0 until totalSongsToSearch) {
            val songObj = songsArray.optJSONObject(i) ?: continue
            val title = songObj.optString("title").trim()
            val artist = songObj.optString("artist").trim()

            if (title.isBlank()) continue

            onProgress("Resolving \"$title\" by $artist...", i + 1, totalSongsToSearch)
            AppLogger.i("Searching InnerTube for AI track: $title - $artist")

            try {
                val query = if (artist.isNotBlank()) "$title $artist" else title
                val searchResults = innerTubeClient.search(query)
                val bestMatch = searchResults.firstOrNull()

                if (bestMatch != null) {
                    resolvedTracks.add(bestMatch)
                } else {
                    AppLogger.w("Could not find InnerTube stream for: $query")
                }
            } catch (e: Exception) {
                AppLogger.e("Error resolving track $title: ${e.message}")
            }
        }

        if (resolvedTracks.isEmpty()) {
            AppLogger.e("No tracks could be resolved from InnerTube")
            onProgress("Could not find matching audio streams for generated songs.", 0, songCount)
            return@withContext null
        }

        onProgress("Building \"$playlistName\" (${resolvedTracks.size} songs)...", totalSongsToSearch, totalSongsToSearch)

        val newPlaylistId = localDatabase.createPlaylist(playlistName, playlistDesc)
        localDatabase.addTracksToPlaylist(newPlaylistId, resolvedTracks)

        AppLogger.i("Successfully generated AI playlist '$playlistName' (id: $newPlaylistId) with ${resolvedTracks.size} tracks")
        onProgress("Playlist ready!", totalSongsToSearch, totalSongsToSearch)

        AiGeneratedPlaylistResult(
            playlistId = newPlaylistId,
            name = playlistName,
            description = playlistDesc,
            tracks = resolvedTracks
        )
    }

    private fun callAiLlm(
        userPrompt: String,
        systemPrompt: String,
        apiKey: String,
        provider: String
    ): String? {
        return if (apiKey.isNotBlank()) {
            callOpenRouter(userPrompt, systemPrompt, apiKey)
                ?: callPollinationsFreeFallback(userPrompt, systemPrompt)
        } else {
            callPollinationsFreeFallback(userPrompt, systemPrompt)
        }
    }

    private fun callOpenRouter(
        userPrompt: String,
        systemPrompt: String,
        apiKey: String
    ): String? {
        try {
            val payload = JSONObject().apply {
                put("model", "google/gemini-2.0-flash-lite:free")
                put("messages", JSONArray().apply {
                    put(JSONObject().apply {
                        put("role", "system")
                        put("content", systemPrompt)
                    })
                    put(JSONObject().apply {
                        put("role", "user")
                        put("content", userPrompt)
                    })
                })
            }

            val request = Request.Builder()
                .url("https://openrouter.ai/api/v1/chat/completions")
                .header("Authorization", "Bearer $apiKey")
                .header("HTTP-Referer", "https://uta-verse.web.app")
                .header("X-Title", "UTA-WAVE Music")
                .post(payload.toString().toRequestBody("application/json".toMediaType()))
                .build()

            httpClient.newCall(request).execute().use { response ->
                if (!response.isSuccessful) {
                    AppLogger.w("OpenRouter failed with HTTP ${response.code}: ${response.message}")
                    return null
                }
                val bodyStr = response.body?.string() ?: return null
                val json = JSONObject(bodyStr)
                val choices = json.optJSONArray("choices") ?: return null
                return choices.optJSONObject(0)?.optJSONObject("message")?.optString("content")
            }
        } catch (e: Exception) {
            AppLogger.e("OpenRouter call failed: ${e.message}", e)
            return null
        }
    }

    private fun callPollinationsFreeFallback(
        userPrompt: String,
        systemPrompt: String
    ): String? {
        try {
            val payload = JSONObject().apply {
                put("model", "openai")
                put("jsonMode", true)
                put("messages", JSONArray().apply {
                    put(JSONObject().apply {
                        put("role", "system")
                        put("content", systemPrompt)
                    })
                    put(JSONObject().apply {
                        put("role", "user")
                        put("content", userPrompt)
                    })
                })
            }

            val request = Request.Builder()
                .url("https://text.pollinations.ai/openai")
                .post(payload.toString().toRequestBody("application/json".toMediaType()))
                .build()

            httpClient.newCall(request).execute().use { response ->
                if (!response.isSuccessful) {
                    AppLogger.w("Pollinations AI failed with HTTP ${response.code}")
                    return null
                }
                val bodyStr = response.body?.string() ?: return null
                val json = JSONObject(bodyStr)
                val choices = json.optJSONArray("choices")
                if (choices != null && choices.length() > 0) {
                    return choices.optJSONObject(0)?.optJSONObject("message")?.optString("content")
                }
                return bodyStr
            }
        } catch (e: Exception) {
            AppLogger.e("Pollinations fallback failed: ${e.message}", e)
            return null
        }
    }

    private fun cleanJsonString(raw: String): String {
        var str = raw.trim()
        if (str.startsWith("```json")) {
            str = str.removePrefix("```json")
        } else if (str.startsWith("```")) {
            str = str.removePrefix("```")
        }
        if (str.endsWith("```")) {
            str = str.removeSuffix("```")
        }
        val firstBrace = str.indexOf('{')
        val lastBrace = str.lastIndexOf('}')
        if (firstBrace != -1 && lastBrace != -1 && lastBrace > firstBrace) {
            str = str.substring(firstBrace, lastBrace + 1)
        }
        return str.trim()
    }
}
